# Packs files for the web shell (..\web), so index.html works when opened straight from disk:
#   web\brains.js         comp.js and chord-name.js, each wrapped in its own scope (they share
#                         global names such as split, has, NAMES), with the same outlet()
#                         interface Max gives them. Re-run after every change to either file.
#   web\piano-samples.js  the Salamander Grand Piano mp3s (CC BY 3.0) as base64, one per minor third.
#   web\bass-samples.js   the tonejs-instruments electric bass mp3s (CC BY 3.0), one per minor third (pop styles).
#   web\upright-samples.js the VSCO 2 CE pizzicato double bass (CC0), see upright-samples.ps1 (jazz styles).
#   web\drum-samples.js   the VCSL drum one-shots (CC0), see drum-samples.ps1.
# Usage: powershell -File build-web.ps1 [piano folder] [electric bass folder] [double bass folder] [drum folder]
param([string]$Download = "$env:TEMP\salamander-dl", [string]$BassDownload = "$env:TEMP\bass-dl",
	[string]$UprightDownload = "$env:TEMP\upright-dl", [string]$DrumDownload = "$env:TEMP\drums-dl")

$root = Split-Path $PSScriptRoot -Parent
$web = Join-Path $root 'web'
New-Item -ItemType Directory -Force $web | Out-Null
$utf8 = New-Object Text.UTF8Encoding $false

function Wrap($name, $file) {
	$src = [IO.File]::ReadAllText((Join-Path $root $file), [Text.Encoding]::UTF8)
	"  ${name}: function (outlet, arrayfromargs, post) {`n$src`n" +
	"    return { call: function (fn, args) { return eval(fn).apply(null, args || []); } };`n  }"
}
$brains = "// Generated by tools/build-web.ps1 from comp.js and chord-name.js. Do not edit here.`n" +
	"window.BRAINS = {`n" + (Wrap 'comp' 'comp.js') + ",`n" + (Wrap 'chordName' 'chord-name.js') + "`n};`n"
[IO.File]::WriteAllText((Join-Path $web 'brains.js'), $brains, $utf8)

$names = @('A0')
for ($o = 1; $o -le 7; $o++) { $names += "C$o", "Ds$o", "Fs$o", "A$o" }
$names += 'C8'
New-Item -ItemType Directory -Force $Download | Out-Null
$ProgressPreference = 'SilentlyContinue'
$parts = @()
foreach ($n in $names) {
	$f = Join-Path $Download "$n.mp3"
	if (-not (Test-Path $f)) { Invoke-WebRequest -Uri "https://tonejs.github.io/audio/salamander/$n.mp3" -OutFile $f -UseBasicParsing }
	$parts += "  `"$n`": `"" + [Convert]::ToBase64String([IO.File]::ReadAllBytes($f)) + "`""
}
$samples = "// Generated by tools/build-web.ps1. Salamander Grand Piano by Alexander Holm, CC BY 3.0 (see ..\CREDITS.txt).`n" +
	"window.PIANO_SAMPLES = {`n" + ($parts -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $web 'piano-samples.js'), $samples, $utf8)

# bass and drums: each recording trimmed and levelled as for bass.wav / drums.wav, then Ogg Opus
# (no encoder gap at the start, so the hits stay in time), keyed by the MIDI note it sounds
function Encode($file, $filter) {
	$tmp = Join-Path $env:TEMP 'coplay-sample.ogg'
	& ffmpeg -hide_banner -loglevel error -y -i $file -af $filter -c:a libopus -b:a 96k -f ogg $tmp
	[Convert]::ToBase64String([IO.File]::ReadAllBytes($tmp))
}

# electric bass (pop styles): the tonejs-instruments mp3s as they are, one every minor third from C#1
New-Item -ItemType Directory -Force $BassDownload | Out-Null
$bassName = @{ 1 = 'Cs'; 4 = 'E'; 7 = 'G'; 10 = 'As' }
$parts = @()
for ($m = 25; $m -le 73; $m += 3) {
	$n = $bassName[$m % 12] + ([math]::Floor($m / 12) - 1)
	$f = Join-Path $BassDownload "$n.mp3"
	if (-not (Test-Path $f)) { Invoke-WebRequest -Uri "https://raw.githubusercontent.com/nbrosowsky/tonejs-instruments/master/samples/bass-electric/$n.mp3" -OutFile $f -UseBasicParsing }
	$parts += "  `"$m`": `"" + [Convert]::ToBase64String([IO.File]::ReadAllBytes($f)) + "`""
}
$samples = "// Generated by tools/build-web.ps1. Electric bass from tonejs-instruments, CC BY 3.0 (see ..\CREDITS.txt).`n" +
	"window.BASS_SAMPLES = {`n" + ($parts -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $web 'bass-samples.js'), $samples, $utf8)

# double bass (jazz styles)
. (Join-Path $PSScriptRoot 'upright-samples.ps1')
Get-UprightSamples $UprightDownload
$parts = @()
foreach ($m in ($UPRIGHT.Keys | Sort-Object)) {
	$f = Join-Path $UprightDownload $UPRIGHT[$m]
	$parts += "  `"$m`": `"" + (Encode $f ("silenceremove=start_periods=1:start_threshold=-50dB,volume=$(Upright-Gain $f)dB,atrim=0:4,afade=t=out:st=3.7:d=0.3")) + "`""
}
$samples = "// Generated by tools/build-web.ps1. Pizzicato double bass from VSCO 2 Community Edition (Versilian Studios), CC0.`n" +
	"window.UPRIGHT_SAMPLES = {`n" + ($parts -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $web 'upright-samples.js'), $samples, $utf8)

. (Join-Path $PSScriptRoot 'drum-samples.ps1')
Get-DrumSamples $DrumDownload
$parts = @()
foreach ($m in ($DRUMS.Keys | Sort-Object)) {
	$f = Join-Path $DrumDownload $DRUMS[$m][0]
	$parts += "  `"$m`": `"" + (Encode $f (Drum-Filter $f $DRUMS[$m][2])) + "`""
}
$samples = "// Generated by tools/build-web.ps1. Drum one-shots from VCSL (Versilian Community Sample Library), CC0.`n" +
	"window.DRUM_SAMPLES = {`n" + ($parts -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $web 'drum-samples.js'), $samples, $utf8)
